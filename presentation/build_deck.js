stat(s, "stat-structure", 7.1, 1.2, 2.4, "54→26%", "structure errors, SDXL → PAG", PAG);
stat(s, "stat-saturation", 7.1, 2.65, 2.4, "7→82%", "over-saturation, SDXL → FreeU + PAG", FREEU);
stat(s, "stat-worst", 0.5, 3.95, 3.5, "5%", "of judgements picked PAG as worst (SDXL 22%)", PAG);
stat(s, "stat-combo", 4.1, 3.95, 3.5, "42%", "picked FreeU + PAG as worst", C.accent5);
s.addNotes("[5:40–6:20, Speaker B] The failure tags explain the ranking. Plain SDXL's main problem is structure, flagged in 54 percent of judgements; PAG halves that. FreeU also helps structure but pushes colours too far, and stacking FreeU with PAG makes it worse: 82 percent flagged as over-saturated, and that combination is picked as worst most often.");

// ---------- 9 案例 ----------
