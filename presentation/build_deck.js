// 8 分钟课堂展示 slides 生成脚本（pptxgenjs）。
// 运行：NODE_PATH=<装有 pptxgenjs 的 node_modules> node presentation/build_deck.js [apply_theme.js 路径]
// 输出：presentation/sdxl_training_free_enhancement.pptx
const path = require("path");
const pptxgen = require("pptxgenjs");

const HERE = __dirname;
const A = (f) => path.join(HERE, "assets", f);
const OUT = path.join(HERE, "sdxl_training_free_enhancement.pptx");

// 配色与报告图表一致：PAG 蓝、FreeU 橙、DUNE 紫
const THEME = {
  name: "SDXL Training-free",
  headFontFace: "Cambria",
  bodyFontFace: "Calibri",
  colors: {
    dk1: "1F2233", lt1: "FFFFFF", dk2: "4A4F66", lt2: "F2F3F7",
    accent1: "2F6FDE", accent2: "E2662C", accent3: "7A5AA6",
    accent4: "3E8E5E", accent5: "C9473F", accent6: "8A8D99",
    hlink: "2F6FDE", folHlink: "7A5AA6",
  },
};

const pres = new pptxgen();
pres.layout = "LAYOUT_16x9"; // 10 × 5.625 in
pres.title = "Training-free Enhancement of SDXL";
pres.theme = { headFontFace: THEME.headFontFace, bodyFontFace: THEME.bodyFontFace };
const C = pres.SchemeColor;
const PAG = C.accent1, FREEU = C.accent2, DUNE = C.accent3, MUTED = C.accent6;

// ---------- 版式 ----------
pres.defineSlideMaster({
  title: "DARK",
  background: { color: C.text1 },
  objects: [
    { placeholder: { options: { name: "title", type: "title", x: 0.6, y: 1.25, w: 5.6, h: 1.6, fontSize: 38, bold: true, color: C.background1, align: "left", valign: "bottom", margin: 0 }, text: "" } },
    { placeholder: { options: { name: "body", type: "body", x: 0.6, y: 3.05, w: 5.6, h: 1.4, fontSize: 16, color: C.background2, valign: "top", margin: 0 }, text: "" } },
  ],
});
pres.defineSlideMaster({
  title: "CONTENT",
  background: { color: C.background1 },
  objects: [
    { placeholder: { options: { name: "title", type: "title", x: 0.5, y: 0.28, w: 9, h: 0.72, fontSize: 30, bold: true, color: C.text1, align: "left", valign: "middle", margin: 0 }, text: "" } },
    { text: { text: "SDXL · FreeU · PAG · DUNE", options: { x: 0.5, y: 5.22, w: 4, h: 0.25, fontSize: 9, color: MUTED, margin: 0 } } },
  ],
  slideNumber: { x: 9.1, y: 5.22, w: 0.4, h: 0.25, fontSize: 9, color: MUTED, align: "right" },
});

const content = (section, title) => {
  const s = pres.addSlide({ masterName: "CONTENT", sectionTitle: section });
  s.addText(title, { placeholder: "title" });
  return s;
};
const text = (s, t, o) => s.addText(t, { isTextBox: true, margin: 0, fontSize: 15, color: C.text1, valign: "top", ...o });
const card = (s, name, x, y, w, h, fill = C.background2) =>
  s.addShape(pres.shapes.ROUNDED_RECTANGLE, { objectName: name, x, y, w, h, rectRadius: 0.08, fill: { color: fill }, line: { color: fill } });
const stat = (s, name, x, y, w, big, label, color) => {
  text(s, big, { objectName: `${name}-value`, x, y, w, h: 0.75, fontSize: 40, bold: true, color, fontFace: "Cambria" });
  text(s, label, { objectName: `${name}-label`, x, y: y + 0.75, w, h: 0.6, fontSize: 13, color: C.text2 });
};
const arrow = (s, name, x, y, w, color = MUTED) =>
  s.addShape(pres.shapes.LINE, { objectName: name, x, y, w, h: 0, line: { color, width: 1.5, endArrowType: "triangle" } });
const pill = (s, name, x, y, w, label, color) => {
  s.addShape(pres.shapes.ROUNDED_RECTANGLE, { objectName: `${name}-pill`, x, y, w, h: 0.34, rectRadius: 0.17, fill: { color }, line: { color } });
  text(s, label, { objectName: `${name}-text`, x, y, w, h: 0.34, fontSize: 12, bold: true, color: C.background1, align: "center", valign: "middle" });
};

// ---------- 1 标题 ----------
pres.addSection({ title: "Opening" });
let s = pres.addSlide({ masterName: "DARK", sectionTitle: "Opening" });
s.addText("Training-free Enhancement of SDXL", { placeholder: "title" });
s.addText([
  { text: "FreeU · PAG · DUNE: what helps, and at what cost", options: { breakLine: true } },
  { text: " ", options: { breakLine: true, fontSize: 8 } },
  { text: "[Name A] · [Name B] · [Name C]", options: { fontSize: 13, breakLine: true } },
  { text: "Generative AI Technical Review · November 2026", options: { fontSize: 13 } },
], { placeholder: "body" });
s.addImage({ objectName: "hero", path: A("hero.jpg"), x: 6.35, y: 0.9, w: 3.2, h: 3.2, altText: "Two giraffes generated by SDXL with PAG" });
text(s, "SDXL + PAG, prompt p130", { objectName: "hero-caption", x: 6.35, y: 4.18, w: 3.2, h: 0.3, fontSize: 10, color: C.background2 });
s.addNotes("[0:00–0:20, Speaker A] Hi, we compared ways to make a text-to-image model draw better pictures without retraining it. In eight minutes: what the methods do, how we tested them, and what we found.");

// ---------- 2 问题 ----------
pres.addSection({ title: "Background and methods" });
s = content("Background and methods", "SDXL still draws broken structure");
s.addImage({ objectName: "problem-images", path: A("problem_sdxl.jpg"), x: 0.5, y: 1.25, w: 6.1, h: 2.99, altText: "Base SDXL outputs with fused giraffes and extra bottles" });
text(s, "Two giraffes with fused bodies and extra legs", { objectName: "problem-cap-1", x: 0.5, y: 4.32, w: 2.95, h: 0.5, fontSize: 11, color: C.text2 });
text(s, "“A man holding a bottle”: three bottles, tangled hands", { objectName: "problem-cap-2", x: 3.6, y: 4.32, w: 3.0, h: 0.5, fontSize: 11, color: C.text2 });
stat(s, "structure-stat", 7.0, 1.35, 2.5, "54%", "of base-SDXL judgements were tagged with a structure or limb error", C.accent5);
text(s, "Retraining a 3.5B-parameter model is out of reach. Can we fix this at inference time instead?", { objectName: "problem-question", x: 7.0, y: 3.0, w: 2.5, h: 1.4, fontSize: 14 });
s.addNotes("[0:20–0:50, Speaker A] Even a strong model like SDXL still makes structural mistakes: animals with extra legs, hands holding three bottles. In our blind study, over half of the judgements on plain SDXL flagged a structure error. Retraining is expensive, so we look at methods that only change how the model is run.");

// ---------- 3 SDXL 流程 ----------
s = content("Background and methods", "Where the two fixes plug in");
const steps = ["Text prompt", "Two text encoders", "U-Net denoising ×30 steps", "VAE decoder", "1024×1024 image"];
steps.forEach((t, i) => {
  const x = 0.5 + i * 1.875;
  const hot = i === 2;
  s.addShape(pres.shapes.ROUNDED_RECTANGLE, { objectName: `flow-${i}`, x, y: 1.3, w: 1.5, h: 0.85, rectRadius: 0.08, fill: { color: hot ? C.text1 : C.background2 }, line: { color: hot ? C.text1 : C.background2 } });
  text(s, t, { objectName: `flow-${i}-label`, x: x + 0.08, y: 1.3, w: 1.34, h: 0.85, fontSize: 13, bold: hot, color: hot ? C.background1 : C.text1, align: "center", valign: "middle" });
  if (i < 4) arrow(s, `flow-arrow-${i}`, x + 1.53, 1.725, 0.32);
});
card(s, "unet-zoom", 1.9, 2.5, 6.2, 2.4);
text(s, "Inside the U-Net, at every step", { objectName: "unet-zoom-title", x: 2.1, y: 2.6, w: 4, h: 0.3, fontSize: 12, bold: true, color: C.text2 });
[["Down blocks", 2.35, null], ["Mid block", 4.3, PAG], ["Up blocks", 6.25, FREEU]].forEach(([t, x, c], i) => {
  s.addShape(pres.shapes.ROUNDED_RECTANGLE, { objectName: `unet-${i}`, x, y: 3.35, w: 1.4, h: 0.6, rectRadius: 0.06, fill: { color: C.background1 }, line: { color: c || MUTED, width: c ? 2.25 : 1 } });
  text(s, t, { objectName: `unet-${i}-label`, x, y: 3.35, w: 1.4, h: 0.6, fontSize: 13, align: "center", valign: "middle" });
});
arrow(s, "unet-arrow-1", 3.78, 3.65, 0.48);
arrow(s, "unet-arrow-2", 5.73, 3.65, 0.48);
s.addShape(pres.shapes.LINE, { objectName: "skip", x: 3.05, y: 3.12, w: 3.9, h: 0, line: { color: FREEU, width: 1.5, dashType: "dash", endArrowType: "triangle" } });
text(s, "skip connections", { objectName: "skip-label", x: 4.3, y: 2.86, w: 1.4, h: 0.24, fontSize: 10, color: C.text2, align: "center" });
pill(s, "pag-here", 4.3, 4.12, 1.4, "PAG acts here", PAG);
pill(s, "freeu-here", 6.25, 4.12, 1.4, "FreeU acts here", FREEU);
s.addNotes("[0:50–1:45, Speaker A] SDXL starts from random noise in a compressed latent space. A U-Net removes the noise over thirty steps, guided by the text, and a decoder turns the result into a picture. Both methods we test plug into that U-Net loop: FreeU changes how the upsampling blocks mix their inputs; PAG adds an extra prediction at the middle block. Neither one changes the model's weights.");

// ---------- 4 FreeU ----------
s = content("Background and methods", "FreeU: rebalance structure and detail");
text(s, [
  { text: "The U-Net decoder mixes two signals:", options: { bold: true, breakLine: true } },
  { text: "Backbone features carry layout and meaning", options: { bullet: true, breakLine: true } },
  { text: "Skip connections carry fine, high-frequency detail", options: { bullet: true, breakLine: true } },
  { text: "When detail dominates, structure can fall apart. FreeU turns the backbone up and the skip detail down.", options: {} },
], { objectName: "freeu-text", x: 0.5, y: 1.3, w: 4.4, h: 2.6, paraSpaceAfter: 8 });
card(s, "freeu-knobs", 5.3, 1.3, 4.2, 2.6);
text(s, "SDXL settings we used", { objectName: "freeu-knobs-title", x: 5.55, y: 1.45, w: 3.7, h: 0.3, fontSize: 12, bold: true, color: C.text2 });
[["Backbone  ×1.3 / ×1.4", 3.2, FREEU], ["Skip detail  ×0.9 / ×0.2", 1.25, MUTED]].forEach(([t, w, c], i) => {
  const y = 1.95 + i * 0.85;
  s.addShape(pres.shapes.RECTANGLE, { objectName: `freeu-bar-${i}`, x: 5.55, y: y + 0.32, w, h: 0.28, fill: { color: c }, line: { color: c } });
  text(s, t, { objectName: `freeu-bar-${i}-label`, x: 5.55, y, w: 3.7, h: 0.3, fontSize: 13 });
});
stat(s, "freeu-cost", 0.5, 3.95, 4.0, "+3%", "inference time: four multiplications per block", FREEU);
s.addNotes("[1:45–2:45, Speaker B] FreeU starts from one observation. Inside the U-Net, the main path decides the overall layout, while skip connections bring in fine detail. If the detail wins, structure suffers. FreeU simply amplifies the main path and damps the skip path. It is almost free: about three percent extra time.");

// ---------- 5 PAG ----------
s = content("Background and methods", "PAG: learn from a broken prediction");
const pagSteps = [
  ["1", "Predict as usual", "The model predicts the noise to remove, guided by the text."],
  ["2", "Predict again, broken", "Same step, but self-attention is replaced by the identity: the layout falls apart."],
  ["3", "Move away from it", "Push the sample away from the broken prediction (scale 3)."],
];
pagSteps.forEach(([n, h, b], i) => {
  const x = 0.5 + i * 3.1;
  card(s, `pag-step-${n}`, x, 1.3, 2.8, 2.35);
  s.addShape(pres.shapes.OVAL, { objectName: `pag-step-${n}-dot`, x: x + 0.22, y: 1.5, w: 0.5, h: 0.5, fill: { color: PAG }, line: { color: PAG } });
  text(s, n, { objectName: `pag-step-${n}-num`, x: x + 0.22, y: 1.5, w: 0.5, h: 0.5, fontSize: 16, bold: true, color: C.background1, align: "center", valign: "middle" });
  text(s, h, { objectName: `pag-step-${n}-head`, x: x + 0.22, y: 2.15, w: 2.4, h: 0.35, fontSize: 16, bold: true });
  text(s, b, { objectName: `pag-step-${n}-body`, x: x + 0.22, y: 2.55, w: 2.4, h: 1.0, fontSize: 13, color: C.text2 });
  if (i < 2) arrow(s, `pag-arrow-${i}`, x + 2.83, 2.47, 0.24, PAG);
});
stat(s, "pag-cost", 0.5, 3.85, 4.2, "+47%", "inference time: one extra U-Net pass per step", PAG);
text(s, "Like showing the model a deliberately bad draft and saying “not like this”.", { objectName: "pag-analogy", x: 5.0, y: 4.0, w: 4.5, h: 0.8, fontSize: 15, italic: true, color: C.text2 });
s.addNotes("[2:45–4:00, Speaker C] PAG works differently. At every step it asks the model for a second prediction where self-attention is switched off, which produces a version with broken structure. It then steers the image away from that broken version. Think of it as showing the model a bad draft and saying: not like this. The price is one extra pass through the network, so about fifty percent more time.");

// ---------- 6 实验设置 ----------
pres.addSection({ title: "Experiments" });
s = content("Experiments", "Same model, prompts and seeds");
[["150", "COCO captions, 5 categories"], ["5", "settings incl. our DUNE reimplementation"], ["1,000", "images on one NVIDIA A40"], ["3 × 60", "blind four-way human rankings"]]
  .forEach(([v, l], i) => stat(s, `setup-${i}`, 0.5 + i * 2.3, 1.3, 2.1, v, l, C.text1));
card(s, "setup-metrics", 0.5, 3.0, 9.0, 1.85);
text(s, "How we measured", { objectName: "setup-metrics-title", x: 0.75, y: 3.12, w: 4, h: 0.3, fontSize: 12, bold: true, color: C.text2 });
text(s, [
  { text: "CLIPScore: does the image match the text?", options: { bullet: true, breakLine: true } },
  { text: "Similarity to the plain SDXL image: how much did the method change it?", options: { bullet: true, breakLine: true } },
  { text: "Time and memory per image", options: { bullet: true, breakLine: true } },
  { text: "Humans: pick best and worst of 4 shuffled images, tag failures", options: { bullet: true } },
], { objectName: "setup-metrics-list", x: 0.75, y: 3.45, w: 8.5, h: 1.35, fontSize: 14, paraSpaceAfter: 3 });
s.addNotes("[4:00–4:50, Speaker A] To keep it fair, every setting used the same SDXL model, the same 150 COCO captions and the same random seed per prompt, so the only difference is the method. We measured text alignment with CLIPScore, how much each method changes the image, speed and memory, and ran a blind study where three of us ranked four shuffled images for sixty prompts.");

// ---------- 7 指标 vs 人 ----------
s = content("Experiments", "The metric and the raters disagree");
s.addImage({ objectName: "fig-metric-vs-human", path: A("fig_metric_vs_human.png"), x: 0.6, y: 1.15, w: 8.4, h: 3.57, altText: "Slope chart: CLIPScore ranks PAG third, human mean rank ranks PAG first" });
text(s, "CLIPScore only checks whether the named objects are present; it cannot see a fifth leg.", { objectName: "metric-takeaway", x: 0.6, y: 4.78, w: 8.4, h: 0.35, fontSize: 14, italic: true, color: C.text2 });
s.addNotes("[4:50–5:40, Speaker B] Here is our main finding. On the left, the automatic metric: no method beats plain SDXL, and PAG is third. On the right, human judgement: PAG comes first and is almost never picked as worst. The metric checks whether the objects in the caption are there, not whether they are drawn correctly. The cost column shows the trade-off: PAG takes about one and a half times as long.");

// ---------- 8 失败类型 ----------
s = content("Experiments", "PAG fixes structure; stacking saturates");
s.addImage({ objectName: "fig-failure-tags", path: A("fig_failure_tags.png"), x: 0.5, y: 1.25, w: 6.3, h: 2.24, altText: "Heatmap of failure tags per setting" });
