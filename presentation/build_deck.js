text(s, [
  { text: "Columns: SDXL, + FreeU, + PAG, + FreeU + PAG, + DUNE", options: { breakLine: true, fontSize: 12, color: C.text2 } },
  { text: " ", options: { breakLine: true, fontSize: 6 } },
  { text: "SDXL and FreeU fuse the two giraffes and add legs", options: { bullet: true, breakLine: true } },
  { text: "PAG separates them cleanly with natural colour", options: { bullet: true, breakLine: true } },
  { text: "FreeU + PAG: right shapes, poster-like colour", options: { bullet: true } },
], { objectName: "case-notes", x: 6.8, y: 1.3, w: 2.7, h: 3.6, fontSize: 14, paraSpaceAfter: 6 });
