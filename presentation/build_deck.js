// ---------- 10 DUNE ----------
s = content("Experiments", "DUNE (2026): the most conservative fix");
s.addImage({ objectName: "fig-similarity", path: A("fig_similarity.png"), x: 0.5, y: 1.2, w: 6.0, h: 2.2, altText: "CLIP image similarity to SDXL for each setting and for increasing PAG and FreeU strength" });
